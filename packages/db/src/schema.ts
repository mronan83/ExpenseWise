/**
 * A member's expense report: trips, which join 24 hours after their return date, and local
 * expenses (FR-EXP-05, FR-EXP-14, ADR-0029). A trip points at its report, and a local
 * expense too; an expense on a trip goes with its trip.
 */
export const reports = pgTable(
  'reports',
  {
    id: id(),
    orgId: orgId(),
    memberId: uuid('member_id').notNull(),
    title: text('title').notNull(),
    status: reportStatus('status').notNull().default('open'),
    currency: char('currency', { length: 3 }).notNull(),
    /** When an open report closes itself: 28 days after opening, later if reopened. */
    closesAt: timestamp('closes_at', { withTimezone: true }).notNull(),
    /** When it last closed, by the person or on day 28; null while open. */
    closedAt: timestamp('closed_at', { withTimezone: true }),
    submittedAt: timestamp('submitted_at', { withTimezone: true }),
    approvedAt: timestamp('approved_at', { withTimezone: true }),
    settledAt: timestamp('settled_at', { withTimezone: true }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    unique('reports_org_id_id_key').on(t.orgId, t.id),
    // What points at a report names its member too, so a report holds only its member's.
    unique('reports_org_member_id_key').on(t.orgId, t.memberId, t.id),
    foreignKey({
      name: 'reports_member_fk',
      columns: [t.orgId, t.memberId],
      foreignColumns: [members.orgId, members.id],
    }),
    check('reports_currency_iso', isoCurrency(t.currency)),
    check('reports_closed_when_closed', sql`(${t.status} = 'open') = (${t.closedAt} IS NULL)`),
    index('reports_member_status_idx').on(t.orgId, t.memberId, t.status),
  ],
);

export const expenses = pgTable(
  'expenses',
  {
    id: id(),
    orgId: orgId(),
    memberId: uuid('member_id').notNull(),
    tripId: uuid('trip_id'),
    /** The report a local expense is on (FR-EXP-14); null for one on a trip. */
    reportId: uuid('report_id'),
    categoryId: uuid('category_id'),
    status: expenseStatus('status').notNull(),
    source: expenseSource('source').notNull(),
    merchant: text('merchant'),
    transactionDate: date('transaction_date', { mode: 'string' }),
    amountMinor: bigint('amount_minor', { mode: 'number' }),
    currency: char('currency', { length: 3 }),
    homeAmountMinor: bigint('home_amount_minor', { mode: 'number' }),
    fxRate: numeric('fx_rate', { precision: 20, scale: 10 }),
    fxRateDate: date('fx_rate_date', { mode: 'string' }),
    fxSource: text('fx_source'),
    /**
     * When it was bought, as local time HH:MM, and the IANA time zone that time is in: read
     * from its receipt (FR-INT-17), the zone worked out from the place, or set by a person.
     */
    transactionTime: text('transaction_time'),
    timeZone: text('time_zone'),
    /** Where it was bought: the merchant's address as printed, and what was picked out of it. */
    merchantAddress: text('merchant_address'),
    merchantCity: text('merchant_city'),
    merchantRegion: text('merchant_region'),
    /** ISO 3166-1 alpha-2. */
    merchantCountry: char('merchant_country', { length: 2 }),
    notes: text('notes'),
    /**
     * Why a local expense, one on no trip, was for business. Its report can't close without
     * it (FR-EXP-14).
     */
    justification: text('justification'),
    /**
     * When a person last edited the values. From then on a reading of the receipt never
     * overwrites them (ADR-0022); a difference from the receipt shows instead.
     */
    editedAt: timestamp('edited_at', { withTimezone: true }),
    /**
     * A person chose its trip, or chose no trip. From then on filing by date never moves it
     * (ADR-0023).
     */
    tripPinned: boolean('trip_pinned').notNull().default(false),
    /** Corrections to approved expenses are a reversal plus a new version. */
    version: integer('version').notNull().default(1),
    reversalOfId: uuid('reversal_of_id'),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    unique('expenses_org_id_id_key').on(t.orgId, t.id),
    foreignKey({
      name: 'expenses_member_fk',
      columns: [t.orgId, t.memberId],
      foreignColumns: [members.orgId, members.id],
    }),
    foreignKey({
      name: 'expenses_trip_fk',
      columns: [t.orgId, t.tripId],
      foreignColumns: [trips.orgId, trips.id],
    }),
    // Only a local expense points at a report itself; one on a trip goes with its trip.
    foreignKey({
      name: 'expenses_report_fk',
      columns: [t.orgId, t.memberId, t.reportId],
      foreignColumns: [reports.orgId, reports.memberId, reports.id],
    }),
    check('expenses_report_only_when_local', sql`${t.reportId} IS NULL OR ${t.tripId} IS NULL`),
    check(
      'expenses_time_of_day',
      sql`${t.transactionTime} IS NULL OR ${t.transactionTime} ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'`,
    ),
    check(
      'expenses_country_code',
      sql`${t.merchantCountry} IS NULL OR ${t.merchantCountry} ~ '^[A-Z]{2}$'`,
    ),
    foreignKey({
      name: 'expenses_category_fk',
      columns: [t.orgId, t.categoryId],
      foreignColumns: [categories.orgId, categories.id],
    }),
    foreignKey({
      name: 'expenses_reversal_fk',
      columns: [t.orgId, t.reversalOfId],
      foreignColumns: [t.orgId, t.id],
    }),
    check('expenses_currency_iso', sql`${t.currency} IS NULL OR ${isoCurrency(t.currency)}`),
    // From Ready onward an expense is complete: amount, currency and date are known.
    check(
      'expenses_complete_when_ready',
      sql`${t.status} IN ('processing', 'needs_review') OR (${t.amountMinor} IS NOT NULL AND ${t.currency} IS NOT NULL AND ${t.transactionDate} IS NOT NULL)`,
    ),
    // A converted amount is only auditable with its rate, date and source.
    check(
      'expenses_fx_complete',
      sql`(${t.fxRate} IS NULL AND ${t.fxRateDate} IS NULL AND ${t.fxSource} IS NULL) OR (${t.fxRate} IS NOT NULL AND ${t.fxRateDate} IS NOT NULL AND ${t.fxSource} IS NOT NULL AND ${t.homeAmountMinor} IS NOT NULL)`,
    ),
    index('expenses_member_date_idx').on(t.orgId, t.memberId, t.transactionDate),
    index('expenses_trip_idx').on(t.orgId, t.tripId),
    index('expenses_report_idx').on(t.orgId, t.reportId),
    index('expenses_status_idx').on(t.orgId, t.status),
  ],
);

export const receipts = pgTable(
  'receipts',
  {
    id: id(),
    orgId: orgId(),
    memberId: uuid('member_id').notNull(),
    expenseId: uuid('expense_id'),
    source: expenseSource('source').notNull(),
    storageKey: text('storage_key').notNull(),
    contentType: text('content_type').notNull(),
    byteSize: integer('byte_size').notNull(),
    sha256: char('sha256', { length: 64 }).notNull(),
    perceptualHash: text('perceptual_hash'),
    status: receiptStatus('status').notNull().default('processing'),
    /**
     * When it was last compared with its member's other receipts for possible duplicates
     * (FR-INT-18). Null for a receipt read before that check existed, which the release
     * checks once.
     */
    duplicatesCheckedAt: timestamp('duplicates_checked_at', { withTimezone: true }),
    createdAt: createdAt(),
  },
  (t) => [
    unique('receipts_org_id_id_key').on(t.orgId, t.id),
    // Exact-duplicate detection: the same file can't be filed twice in one organization.
    unique('receipts_org_sha256_key').on(t.orgId, t.sha256),
    foreignKey({
      name: 'receipts_member_fk',
      columns: [t.orgId, t.memberId],
      foreignColumns: [members.orgId, members.id],
    }),
    foreignKey({
      name: 'receipts_expense_fk',
      columns: [t.orgId, t.expenseId],
      foreignColumns: [expenses.orgId, expenses.id],
    }),
    check('receipts_sha256_hex', sql`${t.sha256} ~ '^[0-9a-f]{64}$'`),
    check('receipts_byte_size_positive', sql`${t.byteSize} > 0`),
  ],
);

