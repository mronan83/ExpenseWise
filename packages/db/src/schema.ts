/*
 * Schema v1. Conventions (docs/05-architecture.md, ADR-0008):
 * - Every tenant table carries org_id. Row-level security in migration 0001 enforces it.
 * - References between tenant tables are composite (org_id, id) foreign keys, so a row
 *   can never point at another organization's row, even though FK checks bypass RLS.
 * - Money is bigint minor units plus a char(3) ISO 4217 code. Never numeric, never float.
 * - Transaction and travel dates are local calendar dates; instants are timestamptz.
 * - IDs are UUIDv7, generated by the application.
 */

